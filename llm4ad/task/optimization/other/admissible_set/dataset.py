from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from llm4ad.task.optimization.dataset_io import DEFAULT_SPLIT, write_manifest

DEFAULT_DATASET_ID = "admissible_set_v1"
DATA_DIR = Path(__file__).resolve().parent / "data"

DEFAULT_SPLIT_SPECS = {
    "train": {
        "role": "train",
        "dimension": 15,
        "weight": 10,
        "optimal_set_length": 3003,
    },
    "test_12_7": {
        "role": "test",
        "dimension": 12,
        "weight": 7,
        "optimal_set_length": 792,
    },
    "test_21_15": {
        "role": "test",
        "dimension": 21,
        "weight": 15,
        "optimal_set_length": 43596,
    },
    "test_24_17": {
        "role": "test",
        "dimension": 24,
        "weight": 17,
        "optimal_set_length": 237984,
    },
}


def write_default_dataset() -> dict[str, Any]:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    manifest = {
        "dataset_id": DEFAULT_DATASET_ID,
        "task": "admissible_set",
        "version": 1,
        "description": "Fixed admissible-set train/test cases; cases are deterministic and generated by enumeration.",
        "generator": "llm4ad.task.optimization.other.admissible_set.dataset.write_default_dataset",
        "splits": DEFAULT_SPLIT_SPECS,
    }
    return write_manifest(DATA_DIR, manifest)


def load_manifest() -> dict[str, Any]:
    path = DATA_DIR / "manifest.json"
    if not path.exists():
        raise FileNotFoundError(
            f"Admissible-set manifest not found: {path}. "
            "Run `uv run python -m llm4ad.task.optimization.other.admissible_set.generate_dataset`."
        )
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def load_split_case(split: str = DEFAULT_SPLIT) -> dict[str, Any]:
    manifest = load_manifest()
    splits = manifest.get("splits", {})
    if split not in splits:
        available = ", ".join(sorted(splits))
        raise ValueError(f"Unknown admissible-set split `{split}`. Available splits: {available}")
    return {
        "dataset_id": manifest["dataset_id"],
        "task": manifest["task"],
        "split": split,
        **splits[split],
    }
